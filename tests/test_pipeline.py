#!/usr/bin/env python3
"""The inbox pipeline's suite: glTF reading, the camera, the bake, the gates.

    python3 tests/test_pipeline.py

Python rather than GDScript because none of it needs an engine -- the pipeline
runs before Godot is involved, and a failure here should be readable without
waiting for an import pass. `tools/ci.sh test` runs this first, then the
GDScript suite, so one command is still the whole gate.

The model under test is generated by tests/fixtures/make_model.py rather than
committed, because a binary blob is a thing nobody can review in a diff.
"""

