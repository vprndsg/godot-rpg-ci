def _painted(sheet, ox, oy, w, h):
    return sum(1 for y in range(h) for x in range(w)
               if sheet.get(ox + x, oy + y)[3] > 0)


def _width(sheet, ox, oy, w, h):
    columns = [x for x in range(w)
               if any(sheet.get(ox + x, oy + y)[3] > 0 for y in range(h))]
    return (max(columns) - min(columns) + 1) if columns else 0


def main():
    tmp = tempfile.mkdtemp(prefix="port-azure-pipeline-")
    try:
        with quiet():
            path = make_model.main(os.path.join(tmp, "quadruped.glb"))
        model = glb.load(path)

        test_the_reader_understands_a_real_export(model)
        test_the_camera_lands_on_this_project_s_diamond()
        test_an_untouched_model_faces_the_camera()
        test_clip_planning_maps_names_to_the_game_s_vocabulary(model)
        test_a_bake_produces_a_placeable_sprite(model)
        test_the_directions_really_are_the_grid_s(model)
        test_a_malformed_actor_pack_is_reported(tmp)
        test_the_pipeline_will_not_guess_a_licence()
        test_bad_settings_are_caught_before_a_long_bake()
        test_a_sidecar_is_found_beside_its_asset(tmp)
        test_settings_layer_in_the_documented_order()
        test_a_file_the_pipeline_cannot_read_says_so(tmp)
        test_the_matrix_maths_is_right()
        test_the_grid_conversion_keeps_the_model_s_handedness()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    if FAILURES:
        print("\nFAILED  %d of %d checks in the pipeline suite"
              % (len(FAILURES), CHECKS[0]))
        for message in FAILURES:
            print("  x %s" % message)
        return 1
    print("PASSED  %d checks in the pipeline suite" % CHECKS[0])
    return 0


if __name__ == "__main__":
    sys.exit(main())
